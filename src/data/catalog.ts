export function auditCatalog(): { valid: boolean; errors: string[] } {
  const seenIds = new Set<string>();
  const seenSkus = new Set<string>();
  const seenImages = new Set<string>();
  const errors: string[] = [];

  for (const item of VERIFIED_CATALOG) {
    if (seenIds.has(item.id)) errors.push(`Duplicate ID: ${item.id}`);
    seenIds.add(item.id);

    if (seenSkus.has(item.sku)) errors.push(`Duplicate SKU: ${item.sku}`);
    seenSkus.add(item.sku);

    if (seenImages.has(item.image)) errors.push(`Duplicate primary image on ${item.id}: ${item.image}`);
    seenImages.add(item.image);

    if (item.price > item.originalPrice) {
      errors.push(`Invalid pricing on ${item.id}: selling price exceeds original price`);
    }
  }

  return { valid: errors.length === 0, errors };
}